def _sha1_pairs(tickers, dates) -> str:
    s = sorted(f"{t}|{_day(d)}" for t, d in zip(tickers, pd.to_datetime(np.asarray(dates))))
    return hashlib.sha1("\n".join(s).encode("utf-8")).hexdigest()[:16]


def _rows_item(tag, key, t, df) -> tuple:
    if df is None or not len(df):
        return (tag, key, t, None, None, 0, 0.0)
    c = df["Close"].to_numpy(float)
    return (tag, key, t, _day(df.index[0]), _day(df.index[-1]), int(len(df)), round(float(np.nansum(c)), 4))


