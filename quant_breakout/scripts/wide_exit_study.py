    res["data_fp"] = {"now": fp, "registered": DATA_FP, "same": fp == DATA_FP}
    res["live_fp"] = {"n": len(lf), "registered_n": len(LIVE_FP or {}), "diff": ldiff, "now": lf}
    say(f"DATA_FP {'与登记值一致' if fp == DATA_FP else '★ 与登记值不同'}；LIVE_FP {len(lf)} 项、与登记值不同 {len(ldiff)} 项（只记录）")
    if fp != DATA_FP:
        return stop("5：数据指纹与登记值不同")
    # 五-6 B4 重算 = 参照
    mark(res, "6", save, t0)
    pre = b4_prereq(W, tbf, say)
    res["prereq"]["b4"] = {k: v for k, v in pre.items() if k != "base"}
