    mark(res, "candidate", save, t0)                                         # 先决条件过后
    # 候选账户
    cand, RC, SKC, YC, EC = {}, {}, {}, {}, {}
    cov = {}
    for e in ERAS:
        cand[e], RC[e], SKC[e], YC[e], EC[e] = run_acct(W, e, tbf[e], wr["_ptd"][e])
        cov[e] = key_coverage(wr["_ptd"][e], RC[e])
        say(f"WXA 账户 {e} 完成（数字只写在文件里）")
    res["coverage"] = cov
    res["elapsed_s"] = round(time.time() - t0)
    if any(v["found"] < v["n"] for v in cov.values()):
        res["cand_invalid_coverage"] = {"note": COV_INVALID_NOTE, "acct": cand}   # 参数混用 → 不进 cand（md 第一节不列、只写覆盖率）
        save(res)
        return stop("候选覆盖率 < 100%（候选的成交有找不到自己参数键的）")
    res["cand"] = cand
    res["trig"] = trig_count(RB, RC)
    save(res)                                                                # 候选账户算完
    # 池子 WXA 配对
    mark(res, "pools", save, t0)
    NV = {s: pool_nets(W, s, X[s], WIDE, bt, rt) for s in POOLS}
    MM = {s: mature_mask(W["SM"][POOL_SM[s]]["fa"], X[s]["ticker"], X[s]["date"]) for s in POOLS}
    res["pools"] = {s: pool_pair(NB[s], NV[s], MM[s][0], MM[s][1]) for s in POOLS}
    res["elapsed_s"] = round(time.time() - t0)
    save(res)                                                                # 池子算完
    say("池子配对完成（数字只写在文件里）")
    # 第一关
    mark(res, "stage1", save, t0)
    res["stage1"] = stage_one(cand, base, res["pools"])
    res["verdict"], res["say"], res["cap"] = verdict(res["stage1"], res["trig"])
    res["options"] = options(res["verdict"], None)
    res["elapsed_s"] = round(time.time() - t0)
