def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="WXA：一直放宽卖法的账户级检验（--prep 只数个数；--run 只运行一次）")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--prep", action="store_true", help="登记前：冻结缓存、先决条件、只数个数（不算任何收益）")
    g.add_argument("--run", action="store_true", help="只运行一次：第一关 + 只描述（终端不打印任何结果数字与判定）")
    a = ap.parse_args(argv)
    logging.disable(logging.CRITICAL)
    warnings.filterwarnings("ignore")
    t0 = time.time()
    say = lambda s_: print(f"{s_}；{time.time() - t0:.0f}s", flush=True)     # noqa: E731
    if a.prep:
        out = prep(say)
        print(json.dumps(out, ensure_ascii=False, indent=1, default=MU._jsonable))
        return 0
    d = out_dir()
    log_attempt("开始")
    lock = None
    try:
        run_guard(d)                                                         # 1 只运行一次（输出文件）
        lock = take_lock()                                                   # 1 只运行一次（同一时间只有一个 --run）
        res = run(say, save=lambda r: write_json(d / OUT_PARTIAL, r))
    except Stop as s:
        release_lock(lock, d)
        log_attempt(s.stage, s.cause, s.why)
        print(f"停在先决条件 {s.stage}：{s.why}（没有算出任何结果、不算跑过；var/out 没有写）", flush=True)
        return 2
    except BaseException as ex:                                              # 不是写好的停法（例：Ctrl-C）：照实记下再抛出
        started = bool(outputs_exist(d))
        if not started:
            release_lock(lock, d)                                            # 还没写出任何文件 = 没算「跑过」→ 可以原样再跑
        log_attempt("5 起（已写出文件，算跑过）" if started else "1〜4（没有写出任何文件，不算跑过）", ex, "异常逃出 run")
        raise
    write_json(d / OUT_JSON, res)                                            # 先写 json（md 生成出错也不丢结果）
    md = report(res)
    (d / OUT_MD).write_text(md, encoding="utf-8")
    (d / OUT_PARTIAL).unlink(missing_ok=True)
    log_attempt("完成")
    print(f"完成：{d / OUT_JSON}、{d / OUT_MD}（判定和数字只在文件里）", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
