def calmar_of(eq: pd.Series) -> dict:
    """capital_study.seg_stats 同一公式（年数 = 日历跨度 ÷ 365.25），不舍入。"""
    e = pd.Series(eq, dtype=float).dropna()
    if len(e) < 20 or e.iloc[0] <= 0:
        return {"cagr": None, "dd": None, "calmar": None}
    yrs = (e.index[-1] - e.index[0]).days / 365.25
    cagr = ((e.iloc[-1] / e.iloc[0]) ** (1 / yrs) - 1) * 100 if yrs > 0 else None
    dd = float((e / e.cummax() - 1).min() * 100)
    return {"cagr": None if cagr is None else float(cagr), "dd": dd, "calmar": None if cagr is None or dd >= 0 else float(cagr / abs(dd))}


def stationary_index(rng, n: int, T: int, block: int) -> np.ndarray:
    """平稳块自助（Politis & Romano）的日序号：每一步以 1 / block 的概率跳到随机起点，否则接着下一天（循环）。形状 (n, T)。"""
    new = rng.random((n, T)) < 1.0 / block
    new[:, 0] = True
    starts = rng.integers(0, T, size=(n, T))
    pos = np.arange(T)
    s = np.maximum.accumulate(np.where(new, pos, 0), axis=1)
    return (np.take_along_axis(starts, s, axis=1) + (pos - s)) % T


def _calmar_paths(R: np.ndarray, yrs: float) -> np.ndarray:
    E = np.cumprod(1.0 + R, axis=1)
    E = np.concatenate([np.ones((E.shape[0], 1)), E], axis=1)
    with np.errstate(invalid="ignore", divide="ignore", over="ignore"):
        cagr = (E[:, -1] ** (1.0 / yrs) - 1.0) * 100
        dd = (E / np.maximum.accumulate(E, axis=1) - 1.0).min(axis=1) * 100
        return np.where(dd < 0, cagr / np.abs(dd), np.nan)


def block_boot(eq_b: pd.Series, eq_c: pd.Series, n: int = BOOT_N, block: int = BOOT_BLOCK, seed=BOOT_SEED) -> dict:
    """D10：两边的逐日收益用同一组重抽的日序号（配对）→ 每次按 seg_stats 同一公式（年数 = 原窗口的日历跨度）算两边 Calmar 与差（WXA − B4）。
    返回 {ok, n, block, T, n_ok, lo, hi, diffs}（lo / hi = BOOT_Q 分位）。"""
    b, c = pd.Series(eq_b, dtype=float).dropna(), pd.Series(eq_c, dtype=float).dropna()
    idx = b.index.intersection(c.index)
    if len(idx) < 21:
        return {"ok": False, "why": "逐日权益不够", "n": n, "block": block}
    b, c = b[idx], c[idx]
    yrs = (idx[-1] - idx[0]).days / 365.25
    rb, rc = b.to_numpy()[1:] / b.to_numpy()[:-1] - 1, c.to_numpy()[1:] / c.to_numpy()[:-1] - 1
    T = len(rb)
    I = stationary_index(np.random.default_rng(seed), n, T, block)
    d = _calmar_paths(rc[I], yrs) - _calmar_paths(rb[I], yrs)
    f = np.isfinite(d)
    lo, hi = (np.percentile(d[f], BOOT_Q) if f.any() else (np.nan, np.nan))
    return {"ok": bool(f.any()), "n": int(n), "block": int(block), "T": int(T), "n_ok": int(f.sum()), "lo": float(lo), "hi": float(hi), "diffs": d}


