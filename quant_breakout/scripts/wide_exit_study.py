    t0 = time.time()
    env = os.environ.get("QB_DROP_ZERO_VOL")
    if env != ZERO_VOL_ENV:
        raise SystemExit(f"QB_DROP_ZERO_VOL = {env!r}（登记的是 {ZERO_VOL_ENV!r}）→ 停")
    pc = precheck(nkt_required=False, self_required=False)                  # 登记前：NKT 状态与本文件的登记状态只记录
    if not pc["ok"]:
        print(json.dumps(pc, ensure_ascii=False, indent=1, default=MU._jsonable))
        raise SystemExit("先决条件 3 不过：" + "；".join(pc["why"]) + " → 停（没有载入任何数据）")
    W, tbf, tbf_pool, live, info = load(say)
