def mature_mask(fa: dict, tickers, dates, bars: int = MATURE_BARS, data_end=None) -> tuple[np.ndarray, np.ndarray]:
    """成熟 = 这只票自己的行情里信号日在、且之后 ≥ bars 根 K 线。kind ∈ {mature, end_of_window, data_ended, no_signal_day}：
    不成熟里「窗口末尾」= 这只票的行情一直到池子数据的最后一天（data_end；缺省 = fa 里全部票行情最后一天的最大值），否则「行情提前结束」。"""
    if data_end is None:
        last = [df.index[-1] for df in fa.values() if df is not None and len(df)]
        data_end = max(last) if last else None
    data_end = None if data_end is None else pd.Timestamp(data_end)
    kind = []
    for t, d in zip(tickers, pd.to_datetime(np.asarray(dates))):
        df = fa.get(str(t))
        if df is None or not len(df) or pd.Timestamp(d) not in df.index:
            kind.append("no_signal_day")
            continue
        pos = int(df.index.get_loc(pd.Timestamp(d)))
        if len(df) - 1 - pos >= bars:
            kind.append("mature")
        elif data_end is not None and df.index[-1] >= data_end:
            kind.append("end_of_window")
        else:
            kind.append("data_ended")
    k = np.asarray(kind, dtype=object)
    return k == "mature", k


def pool_pair(nb, nv, mature, kind=None) -> dict:
    """只取成熟的 → loop11_common.pair_stats（changed = 成熟配对数）+ 个数：n_all / n_mature / n_immature_end / n_immature_data /
    n_no_signal_day / one_nan（成熟但一边 NaN）/ both_nan / diff_n（成熟配对里结果真的不同的个数）。"""
    nb, nv = np.asarray(nb, float), np.asarray(nv, float)
    m = np.asarray(mature, bool)
    fb, fv = np.isfinite(nb), np.isfinite(nv)
    ok = m & fb & fv
    st = LC.pair_stats(np.where(m, nb, np.nan), np.where(m, nv, np.nan), ok)
    k = np.asarray(kind if kind is not None else np.where(m, "mature", "end_of_window"), dtype=object)
    st.update({"n_all": int(len(nb)), "n_mature": int(m.sum()), "n_immature_end": int((k == "end_of_window").sum()),
               "n_immature_data": int((k == "data_ended").sum()), "n_no_signal_day": int((k == "no_signal_day").sum()),
               "one_nan": int((m & (fb ^ fv)).sum()), "both_nan": int((m & ~fb & ~fv).sum()),
               "diff_n": int((ok & ~np.isclose(np.where(ok, nb, 0.0), np.where(ok, nv, 0.0), atol=1e-9, rtol=0.0)).sum())})
    return st


