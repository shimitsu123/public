def run_acct(W: dict, e: str, tbf_e, ptd: dict | None = None) -> tuple:
    """B4（ptd = None 或 {}）或按笔参数的账户：L6.run(W, e, em_tick=tick[, params_td=ptd])；成交 / skipped / 逐日权益在这次运行之后立刻从
    jq_study.RealLotEngine.LAST[-1] 取。返回 (acct, 成交（含 end）, skipped, years, 逐日权益)。"""
    import jq_study as JS
    import loop6_common as L6
    S = C9.signals(W, e)
    tick = C9.tick_of(S["ticker"], S["date"], tbf_e)
    kw = {"em_tick": tick} if tick else {}
    if ptd is not None:
        kw["params_td"] = ptd
    r = L6.run(W, e, **kw)
    eng = JS.RealLotEngine.LAST[-1]
    tr = pd.DataFrame(eng.st.trades)
    a, b = W["ctx"][e]["windows"][e]
    return C9.acct(r), tr, {str(k): int(v) for k, v in dict(getattr(eng, "skipped", {}) or {}).items()}, dict(r.get("years") or {}), \
        equity_series(eng, a, b)


def b4_prereq(W: dict, tbf: dict, say=print) -> dict:
    """先决条件 6：trendline_study.prereq（规则指纹、same_b4：笔数 / 胜率相同、Calmar 差 ≤ 0.005、0000.T 接线 6 键）+ 8 键接线
    （month_up_dip_study.same_acct）。prereq 直接 SystemExit / 出错 → {"ok": False, "error": …}（不往外抛）。"""
    import loop6_common as L6
    import trendline_study as TS
    try:
        if TS.B4_TOL != B4_TOL:
            raise SystemExit(f"trendline_study.B4_TOL = {TS.B4_TOL} ≠ 登记的 {B4_TOL} → 停")
        pre = TS.prereq(W, tbf, say)
        pre["fp_mine_ok"] = pre.get("fingerprint") == FP
        wired = {}
        for e in ERAS:
            S = C9.signals(W, e)
            tick = C9.tick_of(S["ticker"], S["date"], tbf[e])
            day = pd.Timestamp(W["ctx"][e]["days"][100]).normalize()
            fake = C9.acct(L6.run(W, e, em_tick=tick, exit_tick={"0000.T": frozenset([day])}))
            wired[e] = bool(MU.same_acct(fake, pre["base"][e], KEYS))
            pre.setdefault(e, {})["wired_all_keys"] = wired[e]
        say("接线核对（全部 " + "、".join(KEYS) + "）：" + "、".join(f"{e} {'一致' if v else '★ 不一致'}" for e, v in wired.items()))
        pre["ok"] = bool(pre.get("ok") and pre["fp_mine_ok"] and all(wired.values()))
        return pre
    except (SystemExit, Exception) as ex:                                    # noqa: BLE001
        return {"ok": False, "error": f"SystemExit: {ex}" if isinstance(ex, SystemExit) else MU.err_info(ex), "base": {}}


def wiring(W: dict, tbf: dict, base: dict, say=print) -> dict:
    """先决条件 7（不看候选的收益）：a 空表 = B4（8 键）、成交表在这次运行之后立刻取；b 全部信号放「与 X6 值相同、另一个对象」= B4；
    c a 的 B4 每一笔日本个股成交（含 end）找得到键；d WXA 参数表非空（键数 = 有成交日的信号数；只数键、不跑账户）。
    返回 {"ok", "eras": {…}, "_ptd": {年代: WXA 参数表}, "_b4": {年代: B4 的成交 / skipped / years / 逐日权益}}。"""
    wide = wide_params(W["px"])
    out: dict = {"ok": True, "eras": {}, "_ptd": {}, "_b4": {}}
    for e in ERAS:
        S = C9.signals(W, e)
        fills = LC.fill_dates(C9.days_of(W, e), S["date"])
        acct_a, tr_a, sk_a, yr_a, eq_a = run_acct(W, e, tbf[e], {})
        same = ptd_all(replace(W["px"]), S["ticker"], fills)
        acct_b = run_acct(W, e, tbf[e], same)[0]
        cov = key_coverage(same, tr_a)
        ptd_w = ptd_all(wide, S["ticker"], fills)
        n_fill = int(sum(bool(f) for f in fills))
        r = {"a_same": bool(MU.same_acct(acct_a, base[e], KEYS)), "b_same": bool(MU.same_acct(acct_b, base[e], KEYS)),
             "c_found": cov["found"], "c_n": cov["n"], "d_keys": int(len(ptd_w)), "with_fill": n_fill}
        r["ok"] = bool(r["a_same"] and r["b_same"] and cov["n"] == cov["found"] and 0 < len(ptd_w) == n_fill)
        out["eras"][e] = r
        out["_ptd"][e] = ptd_w
        out["_b4"][e] = {"trades": tr_a, "skipped": sk_a, "years": yr_a, "eq": eq_a}
        out["ok"] &= r["ok"]
        say(f"{e}：接线 a 空表 = B4 {'✓' if r['a_same'] else '✗'}；b 同值另一对象 = B4 {'✓' if r['b_same'] else '✗'}；"
            f"c B4 成交找得到键 {cov['found']} / {cov['n']}；d WXA 参数表 {len(ptd_w)} 个键（有成交日的信号 {n_fill}）")
    out["ok"] = bool(out["ok"])
    return out


