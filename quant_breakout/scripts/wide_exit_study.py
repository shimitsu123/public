def nets(fa: dict, X: pd.DataFrame, p0, spec: dict, bt, rt: float) -> np.ndarray:
    """每个信号的假想单笔（loop11_common.single_net；行情缺 → NaN）。不另做缓存：多一份要证明逐位相同的代码，换几分钟不值（运行只一次）。"""
