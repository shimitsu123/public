def out_dir() -> Path:
    """结果只写在 var/out（不能换目录：换了就能绕过「只运行一次」）。"""
    from qbreak import paths
    return paths.PROJECT_ROOT / "var" / "out"


RUN_FILES = (OUT_JSON, OUT_PARTIAL, OUT_MD, OUT_JSON + ".tmp", OUT_PARTIAL + ".tmp")


def outputs_exist(d: Path) -> list[str]:
    return [f for f in RUN_FILES if (Path(d) / f).exists()]


def run_guard(d: Path) -> None:
    """只运行一次：.json / .partial.json / .md / .json.tmp / .partial.json.tmp 任一已存在 → 停在 1（中途停下的也算跑过）。"""
    hit = outputs_exist(d)
    if hit:
        raise Stop(1, f"var/out/{hit[0]} 已经存在（只运行一次；中途停下的也算跑过：照实记录、由用户决定，不重跑）")


def attempts_path() -> Path:
    return cache_dir() / ATTEMPTS


def lock_path() -> Path:
    """--run 的锁（与 attempts 同一个目录：var/cache，不入库）。"""
    return attempts_path().with_name(LOCK)


def take_lock() -> Path:
    """run_guard 之后立刻建锁（open 'x'：已存在就失败）→ 同一时间只有一个 --run 能往下走（run_guard 到第一份 partial 之间约 2〜3 分钟的窗口）。
    已存在 → 停在 1（不删别人的锁）。内容 = pid 与时间。"""
    p = lock_path()
    p.parent.mkdir(parents=True, exist_ok=True)
    try:
        with open(p, "x", encoding="utf-8") as f:
            f.write(json.dumps({"pid": os.getpid(), "time": datetime.now(timezone.utc).isoformat(timespec="seconds")}) + "\n")
    except FileExistsError:
        raise Stop(1, f"锁文件 var/cache/{LOCK} 已存在（另一个 --run 正在运行，或上一次在载入时被中止；"
                      "确认没有别的 --run 在跑之后删掉这个锁文件再运行）") from None
    return p


def release_lock(lock: Path | None, d: Path) -> bool:
    """只删自己建的锁，而且只在 var/out 还没有任何输出时（= 停在 1〜4、没算「跑过」）；第 5 步起保留（跑过了，锁留着也无妨）。"""
    if lock is None or outputs_exist(d):
        return False
    Path(lock).unlink(missing_ok=True)
    return True


def log_attempt(stage, ex: BaseException | None = None, why: str | None = None) -> None:
    """var/cache/wide_exit_attempts.jsonl（不入库）追加一行：时间、git 版本、停在哪一步、异常类型名（不写异常信息）。"""
    rec = {"time": datetime.now(timezone.utc).isoformat(timespec="seconds"), "git": MU.git_info().get("rev"), "stage": str(stage),
           "error": None if ex is None else type(ex).__name__}
    if why:
        rec["why"] = why
    p = attempts_path()
    p.parent.mkdir(parents=True, exist_ok=True)
    with open(p, "a", encoding="utf-8") as f:
        f.write(json.dumps(rec, ensure_ascii=False) + "\n")


def read_attempts() -> list:
    p = attempts_path()
    if not p.exists():
        return []
    out = []
    for ln in p.read_text(encoding="utf-8").splitlines():
        try:
            out.append(json.loads(ln))
        except ValueError:
            continue
    return out


