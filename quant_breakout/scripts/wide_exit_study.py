def d10_noise(eq_b: dict, eq_c: dict, base: dict) -> dict:
    """D10：每个年代 block_boot（种子 d10_seeds() = [BOOT_SEED, 年代序号]）；合计 = 同一次重抽三个年代的差相加。先自检：B4 由逐日权益重算的 Calmar（3 位）
    = 账户的 calmar，不一致 → 算不出。"""
    chk = {e: (None if calmar_of(eq_b[e])["calmar"] is None else round(calmar_of(eq_b[e])["calmar"], 3)) for e in ERAS}
    bad = [e for e in ERAS if chk[e] is None or (base.get(e) or {}).get("calmar") is None or abs(chk[e] - float(base[e]["calmar"])) > 1e-9]
    if bad:
        return {"ok": False, "why": f"自检：B4 由逐日权益重算的 Calmar 与账户不一致（{'、'.join(bad)}）→ 算不出", "self_check": chk}
    eras, tot, seeds = {}, None, d10_seeds()
    for e in ERAS:
        r = block_boot(eq_b[e], eq_c[e], BOOT_N, BOOT_BLOCK, seeds[e])
        if not r.get("ok"):
            return {"ok": False, "why": f"{e}：{r.get('why', '自助全部算不出')}", "self_check": chk}
        tot = r["diffs"] if tot is None else tot + r["diffs"]
        eras[e] = {k2: r[k2] for k2 in ("lo", "hi", "n_ok", "T")}
    f = np.isfinite(tot)
    lo, hi = np.percentile(tot[f], BOOT_Q) if f.any() else (np.nan, np.nan)
    return {"ok": bool(f.any()), "self_check": chk, "eras": eras, "sum": {"lo": float(lo), "hi": float(hi), "n_ok": int(f.sum())},
            "contains_zero": bool(not f.any() or (lo <= 0 <= hi)), "n": BOOT_N, "block": BOOT_BLOCK, "seeds": seeds, "q": list(BOOT_Q)}


