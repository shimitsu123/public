_TT = {"ticker": object, "entry": object, "exit": object, "reason": object, "hold": float, "net": float, "win": bool, "is_end": bool}


def _empty_tt() -> pd.DataFrame:
    return pd.DataFrame({k: pd.Series(dtype=v) for k, v in _TT.items()})


def trade_table(raw: pd.DataFrame, window, keep_end: bool = True) -> pd.DataFrame:
    """引擎成交 → 窗口内买入（与 leap_confirm.trade_stats 同一判断：a ≤ 买入日 ≤ b；b 为 None → 不设上限）的日本个股：
    ticker / entry / exit / reason / hold / net（%）/ win（pnl > 0）/ is_end（期末未平仓）。keep_end=False → 去掉 end。"""
    t = jp_stock(raw)
    if not len(t):
        return _empty_tt()
    a, b = window
    ed = pd.to_datetime(t["entry_date"])
    m = (ed >= pd.Timestamp(a)) & ((ed <= pd.Timestamp(b)) if b else True)
    t = t[np.asarray(m, bool)]
    if not keep_end:
        t = t[(t["reason"].astype(str) != "end").to_numpy()]
    if not len(t):
        return _empty_tt()
    pnl = t["pnl"].to_numpy(float)
    return pd.DataFrame({"ticker": t["ticker"].astype(str).to_numpy(), "entry": pd.to_datetime(t["entry_date"]).dt.strftime("%Y-%m-%d").to_numpy(),
                         "exit": pd.to_datetime(t["exit_date"]).dt.strftime("%Y-%m-%d").to_numpy(), "reason": t["reason"].astype(str).to_numpy(),
                         "hold": t["hold_days"].to_numpy(float),
                         "net": pnl / (t["shares"].to_numpy(float) * t["entry_px"].to_numpy(float)) * 100,
                         "win": pnl > 0, "is_end": (t["reason"].astype(str) == "end").to_numpy()})


def tstats(tt: pd.DataFrame) -> dict:
    """笔数、胜笔、胜率（%）、每笔（%）；不舍入。"""
    n = int(len(tt))
    if not n:
        return {"n": 0, "wins": 0, "win": None, "mean": None}
    w = int(np.asarray(tt["win"], bool).sum())
    return {"n": n, "wins": w, "win": w / n * 100, "mean": float(np.mean(np.asarray(tt["net"], float)))}


def _closed(tt: pd.DataFrame) -> pd.DataFrame:
    return tt[~np.asarray(tt["is_end"], bool)] if len(tt) else tt


def _d(a, b):
    return None if a is None or b is None else float(a) - float(b)


