def flat(d, pre: str = "") -> dict:
    """嵌套 dict → {"a.b.c": 值}（登记前个数逐项对照用）。"""
    out = {}
    for k, v in (d or {}).items():
        key = f"{pre}{k}"
        if isinstance(v, dict):
            out.update(flat(v, key + "."))
        else:
            out[key] = v
    return out


