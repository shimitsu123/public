def matched_pairs(tb: pd.DataFrame, tc: pd.DataFrame) -> dict:
    """D6：（票, 成交日）两边都有的成交（两边都已平仓的那些算胜率 / 每笔差；卖出日改变的笔数）；只在一边的笔数与它们（已平仓）的胜率 / 每笔。"""
    kb = {(a, b): i for i, (a, b) in enumerate(zip(tb["ticker"], tb["entry"]))} if len(tb) else {}
    kc = {(a, b): i for i, (a, b) in enumerate(zip(tc["ticker"], tc["entry"]))} if len(tc) else {}
    both = sorted(set(kb) & set(kc))
    ib, ic = [kb[k] for k in both], [kc[k] for k in both]
    B, C = tb.iloc[ib].reset_index(drop=True), tc.iloc[ic].reset_index(drop=True)
    if len(both):
        closed = ~np.asarray(B["is_end"], bool) & ~np.asarray(C["is_end"], bool)
        sb, sc = tstats(B[closed]), tstats(C[closed])
        changed = int((np.asarray(B["exit"]) != np.asarray(C["exit"])).sum())
    else:
        closed, sb, sc, changed = np.zeros(0, bool), tstats(_empty_tt()), tstats(_empty_tt()), 0
    ob = tb.iloc[[kb[k] for k in sorted(set(kb) - set(kc))]] if len(kb) else _empty_tt()
    oc = tc.iloc[[kc[k] for k in sorted(set(kc) - set(kb))]] if len(kc) else _empty_tt()
    return {"both": {"n": int(len(both)), "n_closed": int(closed.sum()), "b": sb, "c": sc, "dwin": _d(sc["win"], sb["win"]),
                     "dmean": _d(sc["mean"], sb["mean"]), "exit_changed": changed},
            "only_b": {"n": int(len(ob)), "closed": tstats(_closed(ob))}, "only_c": {"n": int(len(oc)), "closed": tstats(_closed(oc))}}


