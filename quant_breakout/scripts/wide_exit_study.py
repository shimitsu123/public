    if not pre.get("ok"):
        return stop("6：B4 重算 ≠ 参照或 0000.T 接线核对没过")
    # 五-7 WXA 接线核对
    mark(res, "7", save, t0)
    wr = wiring(W, tbf, base, say)
    res["prereq"]["wiring"] = wr["eras"]
    if not wr["ok"]:
        return stop("7：WXA 接线核对没过")
    RB = {e: wr["_b4"][e]["trades"] for e in ERAS}
    # 五-8 登记前个数对照（不停）
    mark(res, "8", save, t0)
    cnt = prep_counts(W, tbf, tbf_pool, buy, RB, {e: len(wr["_ptd"][e]) for e in ERAS})
    res["counts"] = cnt
    res["counts_diff"] = counts_diff(PREP_COUNTS, cnt)
    n_diff = len(res["counts_diff"])
    say("登记前个数 / 运行时：" + ("完全相同" if not n_diff else f"有 {n_diff} 项不同（照实列进 md，不停）"))
    # 五-9 池子基准一致
    mark(res, "9", save, t0)
    bt, _ = LC.bt_rt()
    X = {s: pool_signals(W, s, tbf_pool) for s in POOLS}
    NB = {s: pool_nets(W, s, X[s], BASE, bt, rt) for s in POOLS}
    bm = {}
