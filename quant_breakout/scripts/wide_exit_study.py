def _sum_of(x) -> float:
    if isinstance(x, pd.DataFrame):
        v = x.select_dtypes(include=["number", "bool"]).to_numpy(float)
    else:
        v = pd.to_numeric(pd.Series(x), errors="coerce").to_numpy(float)
    return round(float(np.nansum(v)), 4)


def _live_item(name: str, x, end) -> str:
    if isinstance(x, (pd.Series, pd.DataFrame)) and isinstance(x.index, pd.DatetimeIndex):
        x = x[x.index <= pd.Timestamp(end)]
    n = int(len(x)) if hasattr(x, "__len__") else 0
    first = _day(x.index[0]) if n and isinstance(getattr(x, "index", None), pd.DatetimeIndex) else None
    last = _day(x.index[-1]) if n and isinstance(getattr(x, "index", None), pd.DatetimeIndex) else None
    rec = [name, first, last, n, _sum_of(x) if n else 0.0]
    return hashlib.sha1(json.dumps(rec, ensure_ascii=False).encode("utf-8")).hexdigest()[:8]


