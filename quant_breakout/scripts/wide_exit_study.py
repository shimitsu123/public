def _f(v, fmt="{:+.3f}") -> str:
    if v is None or isinstance(v, bool):
        return "—" if v is None else str(v)
    try:
        x = float(v)
    except (TypeError, ValueError):
        return str(v)
    return "—" if not np.isfinite(x) else fmt.format(x)


def _ok(v) -> str:
    return "✓" if v else "✗"


def _err(x) -> str | None:
    return x.get("error") if isinstance(x, dict) else "没有算"


