def d2_split(W: dict, tbf: dict, base: dict, X: dict, NB: dict, MM: dict, bt, rt: float) -> dict:
    """D2 分解（只描述）：WXA-k = k 4、60 天；WXA-h = k 3、90 天 → 三个年代账户与三个池子成熟配对。
    每次账户运行后同主候选一样核对键覆盖率（key_coverage：这次运行的每一笔日本个股成交，含 end，找得到自己的（票, 成交日）键）→
    coverage[e]；不到 100% = 有成交悄悄退回 X6 参数（参数混用）→ md 那一行标「覆盖率不到 100%，只作参考」。只描述，不改判定。"""
    out = {}
    for name, spec in DESC_SPECS.items():
        px = LC.account_params(W["px"], spec)
        acc, cov = {}, {}
        for e in ERAS:
            S = C9.signals(W, e)
            fills = LC.fill_dates(C9.days_of(W, e), S["date"])
            ptd = ptd_all(px, S["ticker"], fills)
            a, tr, *_ = run_acct(W, e, tbf[e], ptd)
            cov[e] = key_coverage(ptd, tr)
            acc[e] = {**a, "d_calmar": _d(a.get("calmar"), base[e].get("calmar"))}
        pools = {s: pool_pair(NB[s], pool_nets(W, s, X[s], spec, bt, rt), MM[s][0], MM[s][1]) for s in POOLS}
        out[name] = {"spec": spec, "acct": acc, "coverage": cov, "coverage_full": all(v["found"] == v["n"] for v in cov.values()),
                     "pools": pools}
    return out


