def trunc_stats(tb: pd.DataFrame, tc: pd.DataFrame, days, last_day, bars: int = TRUNC_BARS) -> dict:
    """D11「同一截尾」：两边都只算窗口最后一天之前 ≥ bars 个交易日买入的成交（买入位置 ≤ 最后一天的位置 − bars；两边都必然已平仓）。"""
    days = pd.DatetimeIndex(days)
    L = int(days.searchsorted(pd.Timestamp(last_day), side="right")) - 1
    if L - bars < 0:
        return {"cutoff": None, "b": tstats(_empty_tt()), "c": tstats(_empty_tt()), "end_b": 0, "end_c": 0, "dwin": None, "dmean": None}
    cut = days[L - bars]

    def sel(t):
        return t[(pd.to_datetime(t["entry"]) <= cut).to_numpy()] if len(t) else t
    b, c = sel(tb), sel(tc)
    sb, sc = tstats(_closed(b)), tstats(_closed(c))
    return {"cutoff": str(cut.date()), "b": sb, "c": sc, "end_b": int(np.asarray(b["is_end"], bool).sum()) if len(b) else 0,
            "end_c": int(np.asarray(c["is_end"], bool).sum()) if len(c) else 0, "dwin": _d(sc["win"], sb["win"]), "dmean": _d(sc["mean"], sb["mean"])}


def slot_counts(sig: pd.DataFrame, tt: pd.DataFrame, slots: int = SLOTS) -> dict:
    """D5：sig = B4 会买的信号（ticker / date = 信号日 / fill = 成交日 "YYYY-MM-DD" 或 ""）；tt = 这次运行的日本个股成交（含 end）。
    有（票, 成交日）对应成交的 → traded；没有的数信号日收盘时的个股持仓笔数（买入日 ≤ 信号日 < 卖出日，含 end）：≥ slots →「名额满」，否则「其他」。"""
    keys = set(zip(tt["ticker"], tt["entry"])) if len(tt) else set()
    ent = pd.to_datetime(tt["entry"]).to_numpy() if len(tt) else np.asarray([], "datetime64[ns]")
    ext = pd.to_datetime(tt["exit"]).to_numpy() if len(tt) else np.asarray([], "datetime64[ns]")
    out = {"signals": int(len(sig)), "no_fill_day": 0, "traded": 0, "full": 0, "other": 0}
    for t, d, f in zip(sig["ticker"], pd.to_datetime(sig["date"]), sig["fill"]):
        if not f:
            out["no_fill_day"] += 1
            continue
        if (str(t), str(f)) in keys:
            out["traded"] += 1
            continue
        d64 = np.datetime64(pd.Timestamp(d))
        held = int(((ent <= d64) & (d64 < ext)).sum())
        out["full" if held >= slots else "other"] += 1
    return out


def div_bias(hb: float | None, hc: float | None, yields=DIV_YIELD_ASSUMED, days: int = TRADING_DAYS) -> dict:
    """D3 分红口径偏差上限（只描述）：J 年代两边平均持有天数差 × 股息率 ÷ 交易日数（pp / 笔）。"""
    if hb is None or hc is None:
        return {"dhold": None, "lo": None, "hi": None}
    dh = float(hc) - float(hb)
    return {"dhold": dh, "lo": dh * yields[0] / days, "hi": dh * yields[1] / days}


