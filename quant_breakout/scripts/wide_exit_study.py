def cache_files_fp(d=None) -> list:
    """五个缓存文件的 (文件名, 字节数, sha256 前 16 位)；缺 → (文件名, None, None)。"""
    d = Path(d) if d is not None else cache_dir()
    out = []
    for f in CACHE_FILES:
        p = d / f
        if not p.exists():
            out.append((f, None, None))
            continue
        h = hashlib.sha256()
        with open(p, "rb") as fh:
            for chunk in iter(lambda: fh.read(1 << 20), b""):
                h.update(chunk)
        out.append((f, int(p.stat().st_size), h.hexdigest()[:16]))
    return out


