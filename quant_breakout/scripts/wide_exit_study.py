def last_day(W: dict, e: str) -> pd.Timestamp:
    """年代的回测最后一天 = 引擎日历里 ≤ ctx["end"]（没有就用窗口终点）的最后一天。"""
    days = C9.days_of(W, e)
    ctx = W["ctx"][e]
    end = ctx.get("end") or ctx["windows"][e][1]
    d = days[days <= pd.Timestamp(end)] if end else days
    return pd.Timestamp(d[-1])


def b4_sig(W: dict, e: str, buy_e) -> pd.DataFrame:
    """B4 会买的日経225 信号：ticker / date / fill。"""
    S = C9.signals(W, e)
