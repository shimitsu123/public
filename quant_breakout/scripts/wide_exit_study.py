def d11_trunc(W: dict, TB: dict, TC: dict) -> dict:
    out = {e: trunc_stats(TB[e], TC[e], C9.days_of(W, e), last_day(W, e)) for e in ERAS}
    b = pd.concat([_cut(TB[e], out[e]["cutoff"]) for e in ERAS], ignore_index=True)
    c = pd.concat([_cut(TC[e], out[e]["cutoff"]) for e in ERAS], ignore_index=True)
    sb, sc = tstats(_closed(b)), tstats(_closed(c))
    out["all"] = {"b": sb, "c": sc, "dwin": _d(sc["win"], sb["win"]), "dmean": _d(sc["mean"], sb["mean"])}
    return out


def _cut(tt: pd.DataFrame, cutoff) -> pd.DataFrame:
    if cutoff is None or not len(tt):
        return _empty_tt()
    return tt[(pd.to_datetime(tt["entry"]) <= pd.Timestamp(cutoff)).to_numpy()]


def d12_raw(EB: dict, EC: dict, TB: dict, TC: dict, X: dict, NB: dict, NV: dict, MM: dict) -> dict:
    """D12：未舍入的值（由逐日权益重算的 Calmar / 回撤 / 年化；胜笔 / 总笔数；池子 dwin / dmean 不舍入）。"""
    out = {}
    for e in ERAS:
        out[e] = {"b": {**calmar_of(EB[e]), **tstats(_closed(TB[e]))}, "c": {**calmar_of(EC[e]), **tstats(_closed(TC[e]))}}
        cb, cc = out[e]["b"]["calmar"], out[e]["c"]["calmar"]
        out[e]["d_calmar"] = _d(cc, cb)
    ds = [out[e]["d_calmar"] for e in ERAS]
    out["sum_d_calmar"] = None if any(v is None for v in ds) else float(sum(ds))
    b = pd.concat([_closed(TB[e]) for e in ERAS], ignore_index=True)
    c = pd.concat([_closed(TC[e]) for e in ERAS], ignore_index=True)
    sb, sc = tstats(b), tstats(c)
    out["pooled"] = {"b": sb, "c": sc, "dwin": _d(sc["win"], sb["win"]), "dmean": _d(sc["mean"], sb["mean"])}
    pools = {}
    for s in POOLS:
        m = MM[s][0] & np.isfinite(NB[s]) & np.isfinite(NV[s])
        if m.any():
            wb, wv = float((NB[s][m] > 0).mean() * 100), float((NV[s][m] > 0).mean() * 100)
            pools[s] = {"n": int(m.sum()), "dwin": wv - wb, "dmean": float(NV[s][m].mean() - NB[s][m].mean())}
        else:
            pools[s] = {"n": 0, "dwin": None, "dmean": None}
    out["pools"] = pools
    return out


NEED_TT = ("D3", "D4", "D6", "D11", "D12")                                    # 要用窗口内成交表 TB / TC 的只描述项


def describe(ctx: dict, say=print) -> tuple[dict, list]:
    """只描述 D1〜D12：窗口内成交表 TB / TC 与每一项都单独 try（出错 → 记异常类型名与位置，照常往下；判定不依赖它们）。
    TB / TC 建不出来 → 用它们的 NEED_TT 各项记「没有算」，其余照算。"""
    W, tbf, base = ctx["W"], ctx["tbf"], ctx["base"]
    D, errors = {}, []
    try:
        win = {e: W["ctx"][e]["windows"][e] for e in ERAS}
        TB = {e: trade_table(ctx["RB"][e], win[e]) for e in ERAS}
        TC = {e: trade_table(ctx["RC"][e], win[e]) for e in ERAS}
    except (SystemExit, Exception) as ex:                                    # noqa: BLE001
        TB = TC = None
        info = MU.err_info(ex)
        errors.append({"item": "成交表 TB / TC", "error": info})
        say(f"只描述的成交表出错（{type(ex).__name__}）：用它的各项记「没有算」，其余照算")
    jobs = (("D1", lambda: d1_singles(W, ctx["buy"], ctx["bt"], ctx["rt"])),
            ("D2", lambda: d2_split(W, tbf, base, ctx["X"], ctx["NB"], ctx["MM"], ctx["bt"], ctx["rt"])),
            ("D3", lambda: d3_exits(TB, TC)),
            ("D4", lambda: d4_end(TB, TC)),
            ("D5", lambda: d5_slots(W, ctx["buy"], ctx["RB"], ctx["RC"], ctx["SKB"], ctx["SKC"])),
            ("D6", lambda: d6_pairs(TB, TC)),
            ("D7", lambda: d7_years(ctx["YB"], ctx["YC"])),
            ("D8", lambda: d8_pools(ctx["X"], ctx["NB"], ctx["NV"], ctx["MM"], W)),
            ("D9", lambda: d9_known(ctx["res"])),
            ("D10", lambda: d10_noise(ctx["EB"], ctx["EC"], base)),
            ("D11", lambda: d11_trunc(W, TB, TC)),
            ("D12", lambda: d12_raw(ctx["EB"], ctx["EC"], TB, TC, ctx["X"], ctx["NB"], ctx["NV"], ctx["MM"])))
    for name, fn in jobs:
        if TB is None and name in NEED_TT:
            D[name] = {"error": "没有算（成交表 TB / TC 出错，见 errors）"}
            continue
        try:
            D[name] = fn()
        except (SystemExit, Exception) as ex:                                # noqa: BLE001
            info = MU.err_info(ex)
            D[name] = {"error": info}
            errors.append({"item": name, "error": info})
            say(f"只描述 {name} 出错（{type(ex).__name__}）：照实记下，照常往下")
        else:
            say(f"只描述 {name} 完成")
    return D, errors


# ───────────────────────── --run ─────────────────────────
def run(say=print, save=None) -> dict:
    """--run（只运行一次；顺序见文件开头十五）。先决条件 1〜4 停下 → raise Stop（不算跑过）；5 起停下 / 出错 → 照实记录、照常返回（算跑过）。"""
    t0 = time.time()
    save = save or (lambda r: None)
    env = os.environ.get("QB_DROP_ZERO_VOL")
    if env != ZERO_VOL_ENV:
        raise Stop(2, f"QB_DROP_ZERO_VOL = {env!r}（登记的是 {ZERO_VOL_ENV!r}）")
    miss = [k for k in ("DATA_FP", "LIVE_FP", "B4_SNAP", "PREP_COUNTS") if globals()[k] is None]
    if miss:
        raise Stop(2, f"登记没做完（{'、'.join(miss)} 还没写入）")
    try:
        pc = precheck(nkt_required=NKT_REQUIRED)
    except (SystemExit, Exception) as ex:                                    # noqa: BLE001  例：读 registry / research_loop*.json 时 JSONDecodeError
        raise Stop(3, f"先决条件 3 出错（{type(ex).__name__}）", ex) from None
    if not pc["ok"]:
        raise Stop(3, "；".join(pc["why"]))
    try:
        W, tbf, tbf_pool, live, info = load(say)
        pxc = px_check(W["px"])
    except (SystemExit, Exception) as ex:                                    # noqa: BLE001
        raise Stop(4, f"载入出错（{type(ex).__name__}）", ex) from None
    # ── 从这里起：已载入真实数据并开始计算 → 算「跑过」 ──
    res: dict = {"registered": registered(), "git": MU.git_info(), "attempts": read_attempts(), "nkt": pc["nkt"], "frozen": info.get("frozen"),
                 "memo": info.get("memo"), "prereq": {"precheck": pc, "params": pxc}, "stage": "5", "stopped": None, "errors": [],
                 "data_fp": None, "live_fp": None, "b4_snap": None, "counts": None, "base": None, "cand": None, "cand_invalid_coverage": None, "coverage": None, "trig": None,
                 "pools": None, "stage1": None, "describe": None}
    res["verdict"], res["say"], res["cap"] = verdict(None, None, "5（进行中）")
    res["options"] = options(res["verdict"], None)
    res["elapsed_s"] = round(time.time() - t0)

    def stop(where: str) -> dict:
        res["stopped"] = where
        res["verdict"], res["say"], res["cap"] = verdict(None, None, where)
        res["options"] = options(res["verdict"], None)
        res["elapsed_s"] = round(time.time() - t0)
        say(f"停在 {where}（照实写进文件，不重跑）")
        return res

    try:
        mark(res, "5", save, t0)                                             # 开始计算的标记：之后中途停下 / 被杀也算跑过（写不出 → 停在 5：出错）
        return _run_body(res, W, tbf, tbf_pool, live, say, save, stop, t0)
    except (SystemExit, Exception) as ex:                                    # noqa: BLE001
        info = MU.err_info(ex) if not isinstance(ex, SystemExit) else f"SystemExit: {ex}"
        res["errors"].append({"item": f"stage {res.get('stage')}", "error": info})
        if res.get("stage1") is not None and res.get("trig") is not None:   # 第一关已经算完（只描述之后出错）：判定照常
            res["elapsed_s"] = round(time.time() - t0)
            return res
        return stop(f"{res.get('stage')}：出错 {info}")


def mark(res: dict, stage: str, save, t0: float) -> None:
    """进入下一步：res["stage"] = stage 并马上重写 partial（只是写一个 json，很便宜）—— 进程在这一步里被硬杀（OOM、容器重启、SIGKILL；
    main 来不及再写任何东西）时，留下的 partial 照实是「停在 <stage>」。判定还没算出（stage1 是 None）时，partial 的判定跟着当前步骤写
    「没有判定（停在 <stage>（进行中））」；第一关算完之后不动判定。写不出 → 异常交给 run 的 except（停在 <stage>：出错，算跑过）。"""
    res["stage"] = stage
    if res.get("stage1") is None:
        res["verdict"], res["say"], res["cap"] = verdict(None, None, f"{stage}（进行中）")
        res["options"] = options(res["verdict"], None)
    res["elapsed_s"] = round(time.time() - t0)
    save(res)


